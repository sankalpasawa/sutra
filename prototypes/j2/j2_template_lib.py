def meta_schema():
    """The reply the generator sends: an action, a template ref, a spec (the parts of a SpecialisedTemplate it may
    write; code fills in artifact, section, extends, provenance), and a reason. Draft-07, closed objects."""
    field = {"type": "object", "additionalProperties": False,
             "properties": {"name": {"type": "string", "description": "an identifier: letters, digits and _"},
                            "type": {"type": "string", "description": "string, integer, boolean, list[string], "
                                                                      "list[<Object>] or <Object>"},
                            "required": {"type": "boolean"},
                            "description": {"type": "string", "description": "in this business's own words"},
                            "enum": {"type": ["array", "null"], "items": {"type": "string"},
                                     "description": "values from the facts, or null"},
                            "nullable": {"type": "boolean"}},
             "required": ["name", "type", "required", "description", "enum", "nullable"]}
    rule = {"type": "object", "additionalProperties": False,
            "properties": {"rule": {"type": "string", "enum": sorted(j2_rules.RULE_TYPES)},
                           "name": {"type": "string"}, "from": {"type": "string"},
                           "path": {"type": "array", "items": {"type": "string"}},
                           "prefix": {"type": ["string", "null"]}, "target": {"type": ["string", "null"]},
                           "values": {"type": ["array", "null"], "items": {"type": "string"}}},
            "required": ["rule", "name", "from", "path", "prefix", "target", "values"]}
    spec = {"type": ["object", "null"], "additionalProperties": False,
            "properties": {"name": {"type": "string"}, "description": {"type": "string"},
                           "fields": {"type": "array", "items": {"$ref": "#/definitions/Field"}},
                           "objects": {"type": "array", "items": {
                               "type": "object", "additionalProperties": False,
                               "properties": {"name": {"type": "string"},
                                              "fields": {"type": "array", "items": {"$ref": "#/definitions/Field"}}},
                               "required": ["name", "fields"]}},
                           "rules": {"type": "array", "items": {"$ref": "#/definitions/Rule"}}},
            "required": ["name", "description", "fields", "objects", "rules"]}
    return {"$schema": "http://json-schema.org/draft-07/schema#", "type": "object", "additionalProperties": False,
            "definitions": {"Field": field, "Rule": rule},
            "properties": {"reason": {"type": "string"},
                           "action": {"type": "string", "enum": ["reuse", "extend", "create"]},
                           "template": {"type": ["string", "null"], "description": "name@version for reuse/extend"},
                           "spec": spec},
            "required": ["reason", "action", "template", "spec"]}


def _norm_rule(r):
    """A rule from the generator's reply as j2_rules reads it: nulls dropped, a one-item path for a single-path
    rule type made a string."""
    r = {k: v for k, v in (r or {}).items() if v is not None}
    if isinstance(r.get("path"), list) and (r.get("rule") in SINGLE_PATH or len(r["path"]) == 1):
        r["path"] = r["path"][0] if r["path"] else ""
    return r


def specialise(gen, need, base=None, name=None):
    """The deterministic spec the mock generator writes (and a live generator may start from): the base (the
    candidate it extends, or the generic) with descriptions in this business's words, facts_used narrowed to the
    need's facts, the fields the facts and the atom name, and one rule of its own. Facts only, nothing invented."""
    src = base or gen
    fields = [f.model_copy(deep=True) for f in src.fields]
    objects = [o.model_copy(deep=True) for o in src.objects]
    site, btype = need["site"], need["business_type"]
    if base is None:
        for f in fields:
            f.description = (f.description.rstrip(".") + f" (for {site}, a {btype})") if f.description else \
                f"the {f.name.replace('_', ' ')} of {site}'s {need['section']}"
    have = {f.name: f for f in fields}
    facts = list(need["facts"])
    if facts:
        fu = have.get("facts_used")
        vals = sorted(set((fu.enum or []) if fu and base is not None else []) | set(facts))
        if fu is not None:
            fu.enum, fu.description = vals, f"the charter facts this section uses, copied exactly from {site}'s charter"
        else:
            fields.append(FieldSpec(name="facts_used", type="list[string]", required=False, enum=vals,
                                    description=f"the charter facts this section is written from, copied exactly "
                                                f"from {site}'s charter"))
    names = {o.name for o in objects}
    for f, objs in need.get("_derived") or []:
        if f.name in have:
            if f.enum and have[f.name].enum is not None:
                have[f.name].enum = sorted(set(have[f.name].enum) | set(f.enum))
            continue
        fields.append(f.model_copy(deep=True))
        objects += [o.model_copy(deep=True) for o in objs if o.name not in names]
        names |= {o.name for o in objs}
    gnames = {f.name for f in gen.fields}
    own = [dict(r) for r in (base.rules if base else []) if r.get("from") != "facts"]
    fu = next((f for f in fields if f.name == "facts_used" and f.enum), None)
    if fu:
        own.append({"rule": "enum", "path": "facts_used[]", "values": list(fu.enum), "from": "facts",
                    "name": f"facts_used are facts of {site}'s charter"})
    added = [f.name for f in fields if f.name not in gnames]
    label = name or (base.name if base else f"{site} {need.get('label') or need['section']}")
    desc = (f"{need['section']} for {site} ({btype}): the generic {gen.name} fields"
            + (f" plus {', '.join(added)}" if added else "") + f", from {len(facts)} charter fact(s)")
    return {"name": label[:80], "description": desc, "fields": [f.model_dump() for f in fields],
            "objects": [o.model_dump() for o in objects], "rules": own}


def mock_generator(need, gen, cands, hint):
    """The mock generator: deterministic, built from the need's facts only. It does what the code's hint says
    (extend the best candidate, or create), and reuses a template when its fingerprint matches."""
    top = cands[0] if cands else None
    if top and top["fingerprint_match"] and top["has_fields"]:
        return {"action": "reuse", "template": f"{top['name']}@{top['version']}", "spec": None,
                "reason": "the same need (same fingerprint) made this template"}
    if hint == "extend" and top:
        base = get(f"{top['name']}@{top['version']}", need["artifact"], need["section"])
        return {"action": "extend", "template": f"{top['name']}@{top['version']}",
                "spec": specialise(gen, need, base=base),
                "reason": f"{top['name']} v{top['version']} covers {top['score']:.0%} of the need; adding the rest"}
    return {"action": "create", "template": None, "spec": specialise(gen, need),
            "reason": f"no template in the library covers {routing('extend_min')} of this need"}


