def _value_problem(t, spec, item_fields):
    """Why one {value} of a render line names nothing (None when it resolves). item_fields: the fields of the list's
    items for an "each" line ({} for a list of strings), None for a "text" line."""
    path, how, _ = AM.value_spec(spec)
    if how and how not in AM.FILTERS:
        return f"{{{spec}}}: unknown filter {how!r} (known: {', '.join(AM.FILTERS)})"
    if path in ("#", "_"):
        return None if item_fields is not None else f"{{{spec}}} only works in an \"each\" line"
    if item_fields is None:
        return resolve(t, path)
    return None if path.split(".")[0] in item_fields else f"{{{spec}}}: {path!r} is not a field of the list's items"


def render_problems(t, blocks):
    """Every reason a section's render blocks can't be written from its fields ([] when they can)."""
    out, objs, fields = [], _objs(t), {f.name: f for f in t.fields}
    for n, b in enumerate(blocks or [], 1):
        if (b.text is None) == (b.each is None) or (b.each is not None and b.line is None):
            out.append(f"render {n}: a block is either \"text\", or \"each\" with a \"line\"")
            continue
        item_fields = None
        if b.each is not None:
            kind, obj = _parse_type(fields[b.each].type) if b.each in fields else (None, None)
            if kind not in ("list_obj", "list_string"):
                out.append(f"render {n}: each {b.each!r} is not a list field of the template")
                continue
            item_fields = {f.name for f in objs[obj].fields} if kind == "list_obj" and obj in objs else set()
            if b.unless and b.unless not in item_fields:
                out.append(f"render {n}: unless {b.unless!r} is not a field of the list's items")
        try:
            parts = AM.line_parts(b.text if b.text is not None else b.line)
        except ValueError as e:
            out.append(f"render {n}: {e}")
            continue
        for kind, x in parts:
            for spec in ([x] if kind == "value" else [y for k, y in x if k == "value"] if kind == "maybe" else []):
                why = _value_problem(t, spec, item_fields)
                if why:
                    out.append(f"render {n}: {why}")
    return out


def _target_problem(artifact, rule):
    """Why a ref_exists rule's target names nothing (None when it resolves): "this.<path>" is a field of one of this
    artifact's sections, "<artifact>.<path>" a field of one of that artifact's."""
    where, _, path = str(rule.get("target") or "").partition(".")
    other = artifact if where == "this" else where
    if other not in artifacts():
        return f"target {rule.get('target')!r}: {where!r} is not this or an artifact with a template"
    for sec in j2_types.sections(other):
        try:
            g = generic(other, sec)
        except Exception:      # a section that doesn't check is named under its own entry
            continue
        if g is not None and resolve(g, path) is None:
            return None
    return f"target {rule.get('target')!r}: no section of {other} has {path!r}"


def generic_problems(names=None):
    """Every reason a generic.json is not a valid source ([] when all are): each file follows the closed shape, names
    its own artifact, has unique sections, and every template passes the template checks (allowed types, rule paths
    that resolve, render lines that name its fields), builds its model and its transport schema, and its rules and
    render run. Checked for every artifact with a template, or the named ones."""
    out = []
    for a in (names or artifacts()):
        p = j2_types.template_path(a)
        where = os.path.relpath(p, HERE) if p.startswith(HERE) else p
        try:
            with open(p, encoding="utf-8") as f:
                raw = json.load(f)
        except (OSError, ValueError) as e:
            out.append(f"{where}: can't be read ({type(e).__name__}: {e})")
            continue
        try:
            doc = GenericFile.model_validate(raw)
        except Exception as e:
            out += [f"{where}: {x}" for x in AM.errors_of(e)]
            continue
        if doc.artifact != a:
            out.append(f"{where}: artifact is {doc.artifact!r}, but the file is {a}'s")
        secs = [t.section for t in doc.templates]
        if len(set(secs)) != len(secs):
            out.append(f"{where}: a section appears twice")
        if DOCUMENT in secs and secs[-1] != DOCUMENT:
            out.append(f"{where}: the {DOCUMENT} template comes last")
        if secs == [DOCUMENT]:
            out.append(f"{where}: it needs at least one section")
        for e in doc.templates:
            at = f"{where} {e.section!r}"
            if e.artifact != a or e.version != doc.version:
                out.append(f"{at}: artifact and version must be the file's ({a}, {doc.version})")
            if e.model is not None and not OBJ_RE.match(e.model):
                out.append(f"{at}: model {e.model!r} must be a CapWord identifier")
            try:
                t = generic(a, e.section)
                model = generic_model(a, e.section)
                AM.reply_schema(model, {})
            except Exception as err:      # the template checks (shape_problems) raise with every reason
                out += [f"{at}: {x}" for x in (AM.errors_of(err) if hasattr(err, "errors") else [f"{type(err).__name__}: {err}"])]
                continue
            known = {f.name for f in t.fields} | {f.name for o in t.objects for f in o.fields}
            for n in e.reply_optional or []:
                if n not in known:
                    out.append(f"{at}: reply_optional names {n!r}, which is not a field")
            for r in e.requires_one_of:
                out += [f"{at}: requires_one_of names {n!r}, which is not a field" for n in r.fields
                        if n not in {f.name for f in t.fields}]
            if e.section == DOCUMENT:
                if e.rules or e.render or e.conditions:
                    out.append(f"{at}: rules, render and conditions belong to the sections")
                continue
            out += [f"{at}: {x}" for x in render_problems(t, e.render)]
            for r in t.rules:
                if r.get("rule") == "ref_exists":
                    why = _target_problem(a, r)
                    if why:
                        out.append(f"{at}: rule {r.get('name')!r}: {why}")
            broke = [r["evidence"] for r in j2_rules.run_rules(a, e.section, {}, {}) if "could not run" in str(r["evidence"])
                     or "unknown rule type" in str(r["evidence"])]
            out += [f"{at}: {x}" for x in broke]
            try:
                AM.render_section(a, e.section, {})
            except Exception as err:
                out.append(f"{at}: render fails on empty data ({type(err).__name__}: {err})")
    return out


