DOCUMENT = AM.DOCUMENT      # agent-views/1: the document-level generic template (the whole document, not one section)
_GENERIC = {}               # id of a generic.json entry -> (the entry, its GenericTemplate)


def document_model(artifact):
    """The whole-document model when the artifact's generic.json has a document-level template, else None."""
    return AM.doc_model(artifact) if j2_types.document(artifact) is not None else None


def generic_model(artifact, section):
    """The model of one generic template: a section's, or the whole document's for the section "Document"."""
    return document_model(artifact) if section == DOCUMENT else AM.section_models(artifact).get(section)


def document_render(artifact):
    """The human-readable template of a document: how its data renders to markdown, section by section (render_section),
    as the headings the parsers and conditions read."""
    model = document_model(artifact)
    file = j2_types.info(artifact)["file"] if artifact in j2_types.names() else f"{artifact}.md"
    return {"format": "markdown", "file": file, "title": f"# {model.template()}" if model else "",
            "sections": [{"heading": f"## {t['section']}", "template": t["name"], "fields": [f["name"] for f in t["fields"]]}
                         for t in j2_types.template(artifact)],
            "from": "j2_artifact_models.render_section(kind, section, data), one section after the other, in this order"}


def generic(artifact, section):
    """The GenericTemplate of one section, read from its artifact's generic.json (None when there is none). The section
    "Document" is the whole document's template (agent-views/1), its objects taken from the sections."""
    artifact = str(artifact or "")
    entry = j2_types.document(artifact) if section == DOCUMENT else j2_types.section_template(artifact, section)
    if entry is None:
        return None
    hit = _GENERIC.get(id(entry))
    if hit is not None and hit[0] is entry:
        return hit[1]
    fields, objects = AM.entry_spec(artifact, entry)
    t = GenericTemplate(name=entry["name"], artifact=artifact, section=section, version=entry.get("version") or AM.VERSION,
                        description=entry.get("description") or "", fields=fields, objects=objects,
                        rules=[dict(r) for r in entry.get("rules") or []])
    t.sha = t.compute_sha()
    _GENERIC[id(entry)] = (entry, t)
    return t


def generic_sections(artifact):
    """Every generic section of an artifact, the Document last when its file has one."""
    return list(j2_types.sections(artifact)) + ([DOCUMENT] if j2_types.document(artifact) is not None else [])


