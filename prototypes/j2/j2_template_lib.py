def save_into_run(run_dir, rec, t=None):
    """Copy the chosen template version into the run (J2_TEMPLATE_LIBRARY=1): a specialised one's four files from
    the library, a generic one's spec, model, schema and meta generated here with kind "generic". The same version
    is copied once. Returns the path relative to the run (None when nothing could be saved)."""
    rel = run_tpl_rel(rec)
    dst = os.path.join(run_dir, rel)
    if os.path.isfile(os.path.join(dst, "spec.json")):
        return rel
    if t is not None:
        src = vdir(t.artifact, t.section, slug(t.name), t.version)
        if not all(os.path.isfile(os.path.join(src, n)) for n in FILES):
            return None
        os.makedirs(dst, exist_ok=True)
        for n in FILES:
            shutil.copyfile(os.path.join(src, n), os.path.join(dst, n))
        return rel
    g = generic(rec["artifact"], rec["section"])
    if g is None:
        return None
    spec = g.model_dump(exclude_none=True)
    schema = AM.transport_schema(AM.SECTION_MODELS[g.artifact][g.section])
    src_text = codegen_generic(g)
    _write(os.path.join(dst, "spec.json"), spec)
    _write(os.path.join(dst, "schema.json"), schema)
    _write(os.path.join(dst, "model.py"), src_text)
    _write(os.path.join(dst, "meta.json"), {"schema": SCHEMA, "name": g.name, "version": g.version, "kind": "generic",
                                            "sha": g.sha, "schema_sha": sha_of(schema),
                                            "model_sha": hashlib.sha256(src_text.encode("utf-8")).hexdigest(),
                                            "used_by": []})
    return rel


def run_templates(run_dir):
    """GET /api/run-templates: the run's decisions, each with where its template can be read from now: "from this
    run" (its saved copy), "from library" (the library has that version), else "not recorded"."""
    rec = _read(os.path.join(run_dir, "templates.json")) if run_dir else None
    out = []
    for d in (rec or {}).get("decisions") or []:
        out.append({**d, "source": _source(run_dir, d)})
    return out


def _source(run_dir, d):
    if run_saved_dir(run_dir, d):
        return "from this run"
    if d.get("kind") == "generic":
        return "from library" if generic(d.get("artifact"), d.get("section")) else "not recorded"
    return "from library" if load(d["artifact"], slug(d["section"]), slug(d["template"]), d["version"]) else "not recorded"


def get(ref, artifact, section):
    """A stored SpecialisedTemplate by "name@version" (or by slug), with its used_by from meta.json; None if absent."""
    name, _, ver = str(ref or "").rpartition("@")
    if not name or not ver.lstrip("v").isdigit():
        return None
    for e in index()["templates"]:
        if e["artifact"] == artifact and e["section"] == section and (e["name"] == name or e["slug"] == slug(name)):
            v = next((x for x in e["versions"] if x["version"] == int(ver.lstrip("v"))), None)
            if not v:
                return None
            got = load(artifact, slug(section), e["slug"], v["version"])
            if not got:
                return None
            spec, meta, _ = got
            return SpecialisedTemplate.model_validate({**spec, "used_by": meta.get("used_by") or []})
    return None


def store(t, fingerprint=None):
    """Write a specialised template, checked again here: (template, version, created). The same sha is the same
    version (nothing written); any change is v<N+1>. Versions are immutable."""
    data = t.model_dump() if isinstance(t, BaseModel) else dict(t)
    data.pop("used_by", None)
    t = SpecialisedTemplate.model_validate({**data, "used_by": []})      # checked at every write
    sha = t.compute_sha()
    idx = index()
    tslug = slug(t.name)
    entry = next((e for e in idx["templates"] if e["artifact"] == t.artifact and e["section"] == t.section
                  and e["slug"] == tslug), None)
    if entry:
        same = next((v for v in entry["versions"] if v["sha"] == sha), None)
        if same:
            return get(f"{t.name}@{same['version']}", t.artifact, t.section), same["version"], False
        version = max(v["version"] for v in entry["versions"]) + 1
    else:
        version = 1
        entry = {"artifact": t.artifact, "section": t.section, "section_slug": slug(t.section), "slug": tslug,
                 "name": t.name, "kind": "specialised", "extends": t.extends, "versions": []}
        idx["templates"].append(entry)
    t.version, t.sha = version, sha
    d = vdir(t.artifact, t.section, tslug, version)
    spec = t.model_dump(exclude={"used_by"})
    schema = transport(t)
    src = codegen(t)
    _write(os.path.join(d, "spec.json"), spec)
    _write(os.path.join(d, "schema.json"), schema)
    _write(os.path.join(d, "model.py"), src)
    meta = {"schema": SCHEMA, "name": t.name, "version": version, "sha": sha, "schema_sha": sha_of(schema),
            "model_sha": hashlib.sha256(src.encode("utf-8")).hexdigest(), "class": class_name(t),
            "created": time.strftime("%Y-%m-%dT%H:%M:%S"), "fingerprints": [t.context.fingerprint],
            "used_by": []}
    _write(os.path.join(d, "meta.json"), meta)
    entry["versions"].append(_version_row(t, meta))
    entry["description"] = t.description
    _save_index(idx)
    return t, version, True


def _version_row(t, meta):
    return {"version": t.version, "sha": t.sha, "schema_sha": meta["schema_sha"], "description": t.description,
            "fingerprints": list(meta.get("fingerprints") or []), "business_type": t.context.business_type,
            "facts": list(t.context.facts_used), "fields": [f.name for f in t.fields], "enums": _enums(t),
            "made_by": t.made_by.model_dump(), "used_by": list(meta.get("used_by") or [])}


def mark_used(t, use, fingerprint=None):
    """Append a use (run, workflow, atom, action) to the version's meta.json and the index; and the need's
    fingerprint, so the same need reuses it next time."""
    d = vdir(t.artifact, t.section, slug(t.name), t.version)
    meta = _read(os.path.join(d, "meta.json")) or {}
    meta.setdefault("used_by", [])
    if use not in meta["used_by"]:
        meta["used_by"].append(use)
    if fingerprint and fingerprint not in meta.setdefault("fingerprints", []):
        meta["fingerprints"].append(fingerprint)
    _write(os.path.join(d, "meta.json"), meta)
    idx = index()
    for e in idx["templates"]:
        if e["artifact"] == t.artifact and e["section"] == t.section and e["slug"] == slug(t.name):
            for v in e["versions"]:
                if v["version"] == t.version:
                    v["used_by"], v["fingerprints"] = meta["used_by"], meta["fingerprints"]
    _save_index(idx)


# ---------------------------------------------------------------- the need: what a workflow's section must carry
LIST_EACH = re.compile(r"(\w+),? each with ([\w ,'-]+?)(?:\s+in\s+[\w ]+)?\.?$", re.I)
LIST_FIELDS = re.compile(r"(\w+) form with the fields ([\w ,'-]+?)\.?$", re.I)
STOP = {"the", "and", "with", "this", "that", "page", "section", "every", "each", "from", "into", "their", "they",
        "what", "when", "have", "has", "shows", "show", "lists", "list", "written", "must", "work", "works", "on",
        "for", "its", "are", "is", "a", "an", "of", "to", "in", "as"}


def words(text):
    return {w for w in re.findall(r"[a-z0-9]+", str(text or "").lower()) if len(w) > 3 and w not in STOP}


def _ident(text):
    s = re.sub(r"[^a-z0-9]+", "_", str(text or "").lower()).strip("_")
    return ("f_" + s if s[:1].isdigit() else s) or "field"


def _split_list(text):
    return [x.strip() for x in re.split(r",\s*|\s+and\s+", text) if x.strip()]


def fact_fields(facts):
    """The fields the charter's own facts name, deterministically: "<things>, each with a, b and c" is a list of
    objects with those fields; "<x> form with the fields a, b and c" is a list of those names. Every name and value is
    copied from a fact; nothing is invented. [(FieldSpec, [ObjectSpec])]."""
    out, seen = [], set()
    for fact in facts:
        m = LIST_EACH.search(fact)
        if m:
            noun, attrs = _ident(m.group(1)), [_ident(a) for a in _split_list(m.group(2))]
            attrs = [a for a in dict.fromkeys(attrs) if NAME_RE.match(a)]
            if noun not in seen and attrs and NAME_RE.match(noun):
                seen.add(noun)
                obj = "".join(p.title() for p in noun.split("_")) + "Item"
                out.append((FieldSpec(name=noun, type=f"list[{obj}]", required=False,
                                      description=f"{fact}; one item each, copied from the charter ([] when the "
                                                  "charter doesn't list them)"),
                            [ObjectSpec(name=obj, fields=[FieldSpec(name=a, type="string", required=True,
                                                                    description=f"the {a.replace('_', ' ')}, as the "
                                                                                "charter gives it")
                                                          for a in attrs])]))
            continue
        m = LIST_FIELDS.search(fact)
        if m:
            name = _ident(m.group(1)) + "_form_fields"
            vals = list(dict.fromkeys(_split_list(m.group(2))))
            if name not in seen and vals and NAME_RE.match(name):
                seen.add(name)
                out.append((FieldSpec(name=name, type="list[string]", required=False, enum=vals,
                                      description=f"the fields of the {m.group(1)} form this section names, from the "
                                                  f"charter: {fact}"), []))
    return out


def fingerprint(artifact, section, business_type, facts, fields=()):
    """sha of (artifact, section, business_type, sorted facts, sorted needed field names)."""
    return sha_of([artifact, section, str(business_type or ""), sorted(set(facts)), sorted(set(fields))])


def make_need(artifact, section, business_type, facts, site, extra_fields=(), workflow="", atom=""):
    """The need of one workflow: artifact + section, business_type, the charter facts behind its items, and the
    fields it asks for (from the facts and the work atom / input documents). Fingerprint by code."""
    facts = sorted(set(str(f) for f in facts if str(f or "").strip()))
    derived = fact_fields(facts) if (artifact, section) in FACT_FIELD_SECTIONS else []
    fields = sorted(set([f.name for f, _ in derived] + [f.name for f, _ in extra_fields]))
    enums = {}
    for f, _ in derived + list(extra_fields):
        if f.enum:
            enums[f.name] = sorted(set(enums.get(f.name, [])) | set(f.enum))
    return {"artifact": artifact, "section": section, "business_type": str(business_type or NOT_RECORDED),
            "facts": facts, "fields": fields, "field_enums": enums, "site": site or NOT_RECORDED,
            "workflow": workflow, "atom": atom,
            "fingerprint": fingerprint(artifact, section, business_type, facts, fields),
            "_derived": derived + list(extra_fields)}


# The sections that carry the business's offer: the facts' own lists become fields here (the requirements of the
# product, and the page section that shows it). Elsewhere the facts narrow facts_used only.
FACT_FIELD_SECTIONS = {("prd", "Requirements"), ("website", "Section")}


def has_field(need, row, name):
    """A template has a needed field when it has the name and, if the need lists values for it (an enum from the
    facts or the LLD), its enum allows every one of them (a field with no enum allows any value)."""
    if name not in (row.get("fields") or []):
        return False
    want = (need.get("field_enums") or {}).get(name)
    have = (row.get("enums") or {}).get(name)
    return not want or have is None or set(want) <= set(have)


def coverage(need, row):
    """(score, facts covered, fields covered): (needed facts it has + needed fields it has) / (all needed). A need
    with nothing in it scores 0: nothing to reuse a template for."""
    facts = set(need["facts"])
    hf = len(facts & set(row.get("facts") or []))
    hd = sum(1 for n in need["fields"] if has_field(need, row, n))
    total = len(facts) + len(need["fields"])
    return (round((hf + hd) / total, 4) if total else 0.0), hf, hd


def candidates(need):
    """Every stored version of the same artifact + section, scored; best first, then newest."""
    out = []
    for e in index()["templates"]:
        if e["artifact"] != need["artifact"] or e["section"] != need["section"]:
            continue
        for v in e["versions"]:
            score, hf, hd = coverage(need, v)
            out.append({"name": e["name"], "slug": e["slug"], "version": v["version"], "score": score,
                        "facts_covered": hf, "fields_covered": hd, "description": v.get("description"),
                        "fields": v.get("fields"), "enums": v.get("enums"),
                        "fingerprint_match": need["fingerprint"] in (v.get("fingerprints") or []),
                        "has_fields": hd == len(need["fields"])})
    out.sort(key=lambda c: (-int(c["fingerprint_match"]), -c["score"], -c["version"], c["name"]))
    return out


# ---------------------------------------------------------------- the generator (one LLM call) and its mock
def meta_schema():
    """The reply the generator sends: an action, a template ref, a spec (the parts of a SpecialisedTemplate it may
    write; code fills in artifact, section, extends, provenance), and a reason. Draft-07, closed objects."""
    field = {"type": "object", "additionalProperties": False,
             "properties": {"name": {"type": "string", "description": "an identifier: letters, digits and _"},
                            "type": {"type": "string", "description": "string, integer, boolean, list[string], "
                                                                      "list[<Object>] or <Object>"},
                            "required": {"type": "boolean"},
                            "description": {"type": "string", "description": "in this business's own words"},
                            "enum": {"type": ["array", "null"], "items": {"type": "string"},
                                     "description": "values from the facts, or null"},
                            "nullable": {"type": "boolean"}},
             "required": ["name", "type", "required", "description", "enum", "nullable"]}
    rule = {"type": "object", "additionalProperties": False,
            "properties": {"rule": {"type": "string", "enum": sorted(j2_rules.RULE_TYPES)},
                           "name": {"type": "string"}, "from": {"type": "string"},
                           "path": {"type": "array", "items": {"type": "string"}},
                           "prefix": {"type": ["string", "null"]}, "target": {"type": ["string", "null"]},
                           "values": {"type": ["array", "null"], "items": {"type": "string"}}},
            "required": ["rule", "name", "from", "path", "prefix", "target", "values"]}
    spec = {"type": ["object", "null"], "additionalProperties": False,
            "properties": {"name": {"type": "string"}, "description": {"type": "string"},
                           "fields": {"type": "array", "items": {"$ref": "#/definitions/Field"}},
                           "objects": {"type": "array", "items": {
                               "type": "object", "additionalProperties": False,
                               "properties": {"name": {"type": "string"},
                                              "fields": {"type": "array", "items": {"$ref": "#/definitions/Field"}}},
                               "required": ["name", "fields"]}},
                           "rules": {"type": "array", "items": {"$ref": "#/definitions/Rule"}}},
            "required": ["name", "description", "fields", "objects", "rules"]}
    return {"$schema": "http://json-schema.org/draft-07/schema#", "type": "object", "additionalProperties": False,
            "definitions": {"Field": field, "Rule": rule},
            "properties": {"reason": {"type": "string"},
                           "action": {"type": "string", "enum": ["reuse", "extend", "create"]},
                           "template": {"type": ["string", "null"], "description": "name@version for reuse/extend"},
                           "spec": spec},
            "required": ["reason", "action", "template", "spec"]}


def _norm_rule(r):
    """A rule from the generator's reply as j2_rules reads it: nulls dropped, a one-item path for a single-path
    rule type made a string."""
    r = {k: v for k, v in (r or {}).items() if v is not None}
    if isinstance(r.get("path"), list) and (r.get("rule") in SINGLE_PATH or len(r["path"]) == 1):
        r["path"] = r["path"][0] if r["path"] else ""
    return r


def specialise(gen, need, base=None, name=None):
    """The deterministic spec the mock generator writes (and a live generator may start from): the base (the
    candidate it extends, or the generic) with descriptions in this business's words, facts_used narrowed to the
    need's facts, the fields the facts and the atom name, and one rule of its own. Facts only, nothing invented."""
    src = base or gen
    fields = [f.model_copy(deep=True) for f in src.fields]
    objects = [o.model_copy(deep=True) for o in src.objects]
    site, btype = need["site"], need["business_type"]
    if base is None:
        for f in fields:
            f.description = (f.description.rstrip(".") + f" (for {site}, a {btype})") if f.description else \
                f"the {f.name.replace('_', ' ')} of {site}'s {need['section']}"
    have = {f.name: f for f in fields}
    facts = list(need["facts"])
    if facts:
        fu = have.get("facts_used")
        vals = sorted(set((fu.enum or []) if fu and base is not None else []) | set(facts))
        if fu is not None:
            fu.enum, fu.description = vals, f"the charter facts this section uses, copied exactly from {site}'s charter"
        else:
            fields.append(FieldSpec(name="facts_used", type="list[string]", required=False, enum=vals,
                                    description=f"the charter facts this section is written from, copied exactly "
                                                f"from {site}'s charter"))
    names = {o.name for o in objects}
    for f, objs in need.get("_derived") or []:
        if f.name in have:
            if f.enum and have[f.name].enum is not None:
                have[f.name].enum = sorted(set(have[f.name].enum) | set(f.enum))
            continue
        fields.append(f.model_copy(deep=True))
        objects += [o.model_copy(deep=True) for o in objs if o.name not in names]
        names |= {o.name for o in objs}
    gnames = {f.name for f in gen.fields}
    own = [dict(r) for r in (base.rules if base else []) if r.get("from") != "facts"]
    fu = next((f for f in fields if f.name == "facts_used" and f.enum), None)
    if fu:
        own.append({"rule": "enum", "path": "facts_used[]", "values": list(fu.enum), "from": "facts",
                    "name": f"facts_used are facts of {site}'s charter"})
    added = [f.name for f in fields if f.name not in gnames]
    label = name or (base.name if base else f"{site} {need.get('label') or need['section']}")
    desc = (f"{need['section']} for {site} ({btype}): the generic {gen.name} fields"
            + (f" plus {', '.join(added)}" if added else "") + f", from {len(facts)} charter fact(s)")
    return {"name": label[:80], "description": desc, "fields": [f.model_dump() for f in fields],
            "objects": [o.model_dump() for o in objects], "rules": own}


def mock_generator(need, gen, cands, hint):
    """The mock generator: deterministic, built from the need's facts only. It does what the code's hint says
    (extend the best candidate, or create), and reuses a template when its fingerprint matches."""
    top = cands[0] if cands else None
    if top and top["fingerprint_match"] and top["has_fields"]:
        return {"action": "reuse", "template": f"{top['name']}@{top['version']}", "spec": None,
                "reason": "the same need (same fingerprint) made this template"}
    if hint == "extend" and top:
        base = get(f"{top['name']}@{top['version']}", need["artifact"], need["section"])
        return {"action": "extend", "template": f"{top['name']}@{top['version']}",
                "spec": specialise(gen, need, base=base),
                "reason": f"{top['name']} v{top['version']} covers {top['score']:.0%} of the need; adding the rest"}
    return {"action": "create", "template": None, "spec": specialise(gen, need),
            "reason": "no template in the library covers half of this need"}


def _prompt(need, gen, cands, hint, refused):
    show = [{k: c[k] for k in ("name", "version", "score", "description", "fields", "enums")} for c in cands[:3]]
    return ("You write the specialised template one J2 workflow's builder will fill. Reply with one JSON object "
            "following the schema.\nTHE NEED: " + json.dumps({k: v for k, v in need.items() if not k.startswith("_")},
                                                              ensure_ascii=False)
            + "\nTHE GENERIC TEMPLATE (keep every required field, with its type; you may narrow a string to an enum "
              "from the facts, add fields, and rewrite descriptions in this business's words): "
            + json.dumps(gen.model_dump(exclude={"sha"}), ensure_ascii=False)
            + "\nTOP CANDIDATES IN THE LIBRARY, scored by code (coverage of the need's facts and fields): "
            + json.dumps(show, ensure_ascii=False)
            + f"\nCODE SUGGESTS: {hint}. reuse = an existing name@version as it is (coverage must be at least 0.5); "
              "extend = a new version of that template (template = its name@version, spec = the whole new spec); "
              "create = a new template (template null). Allowed field types: string, integer, boolean, list[string], "
              f"list[<Object>], <Object> (objects defined in objects); at most {MAX_FIELDS} fields; rule types: "
            + ", ".join(sorted(j2_rules.RULE_TYPES)) + ". Facts only: no fact that is not in the need."
            + (f"\nYOUR LAST REPLY WAS REFUSED: {refused}. Fix that." if refused else ""))


def route(need, ctx, ask=None):
    """Pick the template one workflow's builder fills. ctx: {run, workflow, atom, agent}. ask(system, user, mock,
    schema) is the generator's one LLM call (None: the mock). Returns (template or None for generic, decision)."""
    gen = generic(need["artifact"], need["section"])
    cands = candidates(need)
    top = cands[0] if cands else None
    use = {"run": ctx.get("run"), "workflow": ctx.get("workflow"), "atom": ctx.get("atom")}
    base = {"workflow": ctx.get("workflow"), "atom": ctx.get("atom"), "artifact": need["artifact"],
            "section": need["section"], "fingerprint": need["fingerprint"], "facts": len(need["facts"]),
            "fields": len(need["fields"]), "needed_fields": list(need["fields"]),
            "needed_enums": dict(need.get("field_enums") or {}),
            "candidates": [{k: c[k] for k in ("name", "version", "score", "fingerprint_match", "has_fields")}
                           for c in cands[:3]]}

    def done(t, action, score, reason, **extra):
        rec = {**base, "action": action, "template": t.name if t else (gen.name if gen else NOT_RECORDED),
               "version": t.version if t else AM.VERSION, "kind": "specialised" if t else "generic",
               "score": score, "reason": reason, **extra}
        if t:
            _, hf, hd = coverage(need, {"facts": t.context.facts_used, "fields": [f.name for f in t.fields],
                                        "enums": _enums(t)})
            rec["covers"] = f"covers {hf} of {len(need['facts'])} facts" + (
                f" and {hd} of {len(need['fields'])} fields" if need["fields"] else "")
            mark_used(t, {**use, "action": action}, need["fingerprint"])
            rec["schema_sha"] = sha_of(transport(t))
        elif gen is not None:
            rec["schema_sha"] = sha_of(AM.transport_schema(AM.SECTION_MODELS[need["artifact"]][need["section"]]))
        return t, rec

    if gen is None:
        return None, {**base, "action": "generic", "template": NOT_RECORDED, "version": None, "kind": "generic",
                      "score": None, "reason": f"no generic template for {need['artifact']} {need['section']!r}"}
    cov = lambda c: f"covers {c['facts_covered']} of {len(need['facts'])} facts" + (
        f" and {c['fields_covered']} of {len(need['fields'])} fields" if need["fields"] else "")
    # nothing to specialise: no facts and no extra fields -> the generic template, never a specialised one
    if not need["facts"] and not need["fields"]:
        return done(None, "generic", None, NOTHING_TO_SPECIALISE, rule="0")
    # a) the same fingerprint, and the template has every needed field (with the needed values): this version
    hit = next((c for c in cands if c["fingerprint_match"] and c["has_fields"]), None)
    if hit:
        t = get(f"{hit['name']}@{hit['version']}", need["artifact"], need["section"])
        if t:
            return done(t, "reused", hit["score"], f"same fingerprint: {cov(hit)}", rule="a")
    # b) a candidate that covers everything
    if top and top["score"] >= 1.0:
        t = get(f"{top['name']}@{top['version']}", need["artifact"], need["section"])
        if t:
            return done(t, "reused", top["score"], f"coverage 1.0: {cov(top)}", rule="b")
    hint = "extend" if top and top["score"] >= 0.5 else "create"
    rule = "c" if hint == "extend" else "d"
    refused, tries = None, []
    for attempt in (1, 2):
        mock = lambda: json.dumps(mock_generator(need, gen, cands, hint), ensure_ascii=False)
        try:
            raw = ask(GEN_SYSTEM, _prompt(need, gen, cands, hint, refused), mock, meta_schema()) if ask else mock()
            reply = json.loads(raw) if isinstance(raw, str) else raw
        except Exception as e:      # the generator never blocks the run
            reply, refused = None, f"the generator's reply could not be read ({type(e).__name__}: {e})"
        if reply is not None:
            t, why, score = _accept(reply, need, gen, cands, ctx)
            if t is not None:
                act = {"reuse": "reused", "extend": "extended", "create": "created"}[reply["action"]]
                note = why or str(reply.get("reason") or "")
                if act == "reused":
                    return done(t, act, score, note, rule="b", attempts=attempt, refused=tries)
                return done(t, act, score if act == "extended" else (top["score"] if top else 0.0), note,
                            rule=rule, attempts=attempt, refused=tries)
            refused = why
        tries.append(refused)
    return done(None, "generic", top["score"] if top else 0.0,
                f"the generated spec failed the checks twice ({'; '.join(str(x) for x in tries)[:300]}), so the "
                "builder fills the generic template", rule="e", attempts=2, refused=tries)


NOTHING_TO_SPECIALISE = "no facts or extra fields to specialise"
GEN_SYSTEM = ("You are J2's template generator. You write closed JSON templates for one business, in its own words, "
              "from its recorded facts only. Code checks every reply and refuses anything outside the rules.")


def _accept(reply, need, gen, cands, ctx):
    """(template or None, reason, score). Code re-checks everything: a reuse must exist at that version (and is
    overruled when its coverage is below 0.5); an extend must name a candidate; every spec passes the checks."""
    action = reply.get("action") if isinstance(reply, dict) else None
    if action not in ("reuse", "extend", "create"):
        return None, f"action {action!r} is not reuse, extend or create", 0.0
    if action == "reuse":
        ref = str(reply.get("template") or "")
        c = next((c for c in cands if f"{c['name']}@{c['version']}" == ref), None)
        t = get(ref, need["artifact"], need["section"]) if c else None
        if t is None:
            return None, f"reuse names {ref!r}, which is not in the library at that version", 0.0
        if c["score"] < 0.5:
            return None, (f"code overruled the reuse of {ref}: its coverage is {c['score']:.2f}, below 0.5"), 0.0
        return t, f"the generator reused {ref} (coverage {c['score']:.2f})", c["score"]
    spec = reply.get("spec")
    if not isinstance(spec, dict):
        return None, f"{action} needs a spec", 0.0
    score = 0.0
    if action == "extend":
        ref = str(reply.get("template") or "")
        c = next((c for c in cands if f"{c['name']}@{c['version']}" == ref), None)
        if c is None:
            return None, f"extend names {ref!r}, which is not a candidate", 0.0
        spec = {**spec, "name": c["name"]}
        score = c["score"]
    elif any(c["name"] == spec.get("name") or c["slug"] == slug(spec.get("name")) for c in cands):
        return None, f"a template named {spec.get('name')!r} exists; extend it instead", 0.0
    data = {"name": spec.get("name"), "artifact": need["artifact"], "section": need["section"], "kind": "specialised",
            "description": spec.get("description") or "", "fields": spec.get("fields") or [],
            "objects": spec.get("objects") or [], "rules": [_norm_rule(r) for r in spec.get("rules") or []],
            "extends": generic_ref(need["artifact"], need["section"]),
            "made_by": {"run": str(ctx.get("run") or ""), "workflow": str(ctx.get("workflow") or ""),
                        "atom": str(ctx.get("atom") or ""), "agent": str(ctx.get("agent") or "template generator")},
            "context": {"business_type": need["business_type"], "facts_used": list(need["facts"]),
                        "fingerprint": need["fingerprint"]}}
    for f in data["fields"] + [x for o in data["objects"] for x in (o.get("fields") or [])]:
        if isinstance(f, dict):
            f.setdefault("nullable", False)
            if f.get("enum") is None:
                f.pop("enum", None)
    bad = refusal(data)
    if bad:
        return None, "; ".join(bad)[:400], 0.0
    t, _, _ = store(SpecialisedTemplate.model_validate(data))
    return t, str(reply.get("reason") or ""), score


# ---------------------------------------------------------------- mock builder data, and the readable view
def fill_mock(t, data, need):
    """Mock only: the generic mock data made to fit a specialised template, from the need's facts only - an enum list
    holds its recorded values, an object list stays [] (no fact is invented), a string "not recorded"."""
    out = dict(data or {})
    objs = _objs(t)

    def blank(f):
        kind, obj = _parse_type(f.type)
        if kind == "list_string":
            return list(f.enum or [])
        if kind == "list_obj":
            return []
        if kind == "integer":
            return 0
        if kind == "boolean":
            return False
        if kind == "obj":
            return {g.name: blank(g) for g in objs[obj].fields} if f.required else None
        return (f.enum[0] if f.enum else NOT_RECORDED)
    for f in t.fields:
        v = out.get(f.name)
        if f.name not in out:
            if f.required or f.name == "facts_used" or (f.enum and _parse_type(f.type)[0] == "list_string"):
                out[f.name] = blank(f)
            continue
        if f.enum:
            if isinstance(v, list):
                keep = [x for x in v if x in f.enum]
                out[f.name] = keep or list(f.enum)
            elif v not in f.enum:
                out[f.name] = f.enum[0]
    return out


def rule_sentence(r):
    """A rule as a plain sentence (the Readable view)."""
    p = r.get("path")
    p = ", ".join(p) if isinstance(p, list) else str(p or r.get("anchor_path") or "")
    s = {"ids_sequential": f"{p} ids run {r.get('prefix')}1, {r.get('prefix')}2, ... in order, each once",
         "ids_unique": f"every id in {p} appears once",
         "ref_exists": f"every id named in {p} exists in {r.get('target')}",
         "enum": f"{p} is one of: {', '.join(r.get('values') or [])}",
         "hex": f"every value of {p} is a hex colour", "css_safe": f"{p} hold plain CSS only",
         "html_no_page_tags": f"{p} has no <html>, <head> or <body> tags",
         "anchor_selector": f"{p} is an id selector like #classes",
         "anchor_in_html": f"the anchor points at an element in {r.get('html_path')}",
         "not_empty": f"{p} must be given", "one_of_present": f"at least one of {p} is given",
         "url_prefix": f"{p} starts with {r.get('prefix')} (or is empty)"}.get(r.get("rule"), str(r.get("name")))
    return s[:1].upper() + s[1:] + "."


def library_view():
    """GET /api/library: every template grouped by artifact and section, the generic layer included."""
    groups = {}
    for a in ARTIFACTS:
        for sec in AM.SECTION_MODELS[a]:
            g = generic(a, sec)
            groups.setdefault(a, {})[sec] = {"generic": {"name": g.name, "version": g.version, "sha": g.sha,
                                                         "description": g.description,
                                                         "fields": [f.name for f in g.fields]},
                                             "templates": []}
    for e in index()["templates"]:
        slot = groups.setdefault(e["artifact"], {}).setdefault(e["section"], {"generic": None, "templates": []})
        slot["templates"].append(e)
    return {"schema": SCHEMA, "dir": os.path.relpath(lib_dir(), HERE) if lib_dir().startswith(HERE) else lib_dir(),
            "groups": groups}


def template_view(artifact, section_slug, tslug, version, run_dir=None):
    """GET /api/library/<artifact>/<section>/<slug>/v<N>: the four files with their shas, and the readable form.
    "generic" as the slug serves the generic template (generic.json's entry, its schema and a model listing). With a
    run_dir, the run's own saved copy comes first ("from this run"), then the library ("from library"); a template
    neither has is "not recorded"."""
    if run_dir:
        decs = (_read(os.path.join(run_dir, "templates.json")) or {}).get("decisions") or []
        mine = [d for d in decs if d.get("artifact") == artifact and slug(d.get("section")) == section_slug
                and (slug(d.get("template")) == tslug or (tslug == "generic" and d.get("kind") == "generic"))
                and (tslug == "generic" or d.get("version") == version)]
        for d in mine:
            sd = run_saved_dir(run_dir, d)
            if sd:
                spec, meta, files = load_dir(sd)
                cls = GenericTemplate if spec.get("kind") == "generic" else SpecialisedTemplate
                t = cls.model_validate({**spec, **({"used_by": meta.get("used_by") or []} if cls is SpecialisedTemplate
                                                   else {})})
                return {"template": spec, "meta": meta, "files": _with_sha(files), "readable": readable(t),
                        "source": "from this run", "saved": d.get("saved")}
        got = _library_view_of(artifact, section_slug, tslug, version)
        if got:
            return {**got, "source": "from library"}
        if mine:
            d = mine[-1]
            return {"template": {"name": d.get("template"), "version": d.get("version"), "artifact": artifact,
                                 "section": d.get("section"), "kind": d.get("kind")}, "meta": {}, "files": {},
                    "readable": None, "source": "not recorded", "saved": d.get("saved")}
        return None
    got = _library_view_of(artifact, section_slug, tslug, version)
    return {**got, "source": "from library"} if got else None


def _library_view_of(artifact, section_slug, tslug, version):
    if tslug == "generic":
        sec = next((s for s in AM.SECTION_MODELS.get(artifact, {}) if slug(s) == section_slug), None)
        if sec is None:
            return None
        t = generic(artifact, sec)
        gpath = os.path.join(GENERIC_DIR, artifact, "generic.json")
        try:
            with open(gpath, encoding="utf-8") as f:
                gtext = f.read()
        except OSError:
            gtext = None
        schema = AM.transport_schema(AM.SECTION_MODELS[artifact][sec])
        stext = json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        spec = t.model_dump(exclude_none=True)
        files = {"generic.json": gtext, "spec.json": json.dumps(spec, indent=2, ensure_ascii=False) + "\n",
                 "model.py": codegen_generic(t), "schema.json": stext}
        return {"template": spec, "meta": {"used_by": [], "kind": "generic"}, "files": _with_sha(files),
                "readable": readable(t)}
    got = load(artifact, section_slug, tslug, version)
    if not got:
        return None
    spec, meta, files = got
    t = SpecialisedTemplate.model_validate({**spec, "used_by": meta.get("used_by") or []})
    return {"template": spec, "meta": meta, "files": _with_sha(files), "readable": readable(t)}


def codegen_generic(t):
    """The generic template's model listing, from the same codegen (the runtime generic is the model itself)."""
    head = f"# The generic template is j2_artifact_models.{AM.SECTION_MODELS[t.artifact][t.section].__name__}; this " \
           "listing is codegen() of its generic.json entry.\n"
    return head + codegen(t)


def run_example(run_dir, spec, tslug):
    """The data a run's builder sent for this template's section, when the run used this template (else None)."""
    rec = _read(os.path.join(run_dir, "templates.json")) or {}
    used = [d for d in rec.get("decisions") or [] if d.get("artifact") == spec.get("artifact")
            and d.get("section") == spec.get("section")
            and (slug(d.get("template")) == tslug or (tslug == "generic" and d.get("kind") == "generic"))
            and (tslug == "generic" or d.get("version") == spec.get("version"))]
    if not used:
        return None
    doc = _read(os.path.join(run_dir, f"{spec.get('artifact')}.json")) or {}
    data = (doc.get("sections") or {}).get(spec.get("section"))
    return {"workflow": used[-1].get("workflow"), "data": data} if data else None


def _with_sha(files):
    return {n: {"text": v, "sha": hashlib.sha256(v.encode("utf-8")).hexdigest() if v is not None else None}
            for n, v in files.items()}


def readable(t):
    objs = _objs(t)
    row = lambda f: {"name": f.name, "type": f.type, "required": f.required, "description": f.description,
                     "enum": f.enum or [], "nullable": f.nullable}
    gen = generic(t.artifact, t.section) if t.kind == "specialised" else None
    gnames = {f.name for f in gen.fields} if gen else None
    return {"name": t.name, "version": t.version, "kind": t.kind, "artifact": t.artifact, "section": t.section,
            "description": t.description, "extends": getattr(t, "extends", None),
            "fields": [{**row(f), "added": gnames is not None and f.name not in gnames} for f in t.fields],
            "objects": [{"name": o.name, "fields": [row(f) for f in o.fields]} for o in t.objects],
            "rules": ([{"sentence": rule_sentence(r), "from": r.get("from"), "own": False}
                       for r in (gen.rules if gen else [])]
                      + [{"sentence": rule_sentence(r), "from": r.get("from"), "own": t.kind == "specialised"}
                         for r in t.rules])}


