"""template-library/1: every artifact section is a GENERIC template (the fixed layout of its artifact type) plus, per
workflow, a SPECIALISED template generated from the workflow's context and kept in a library (J2_TEMPLATE_LIBRARY=1,
which implies J2_ARTIFACT_SCHEMA=1).

Template is a base class of the interface library, beside Workflow and Step: a closed model, checked at every write.
    GenericTemplate      read FROM templates/<artifact>/generic.json, the hand-edited source of an artifact's sections,
                         fields and rules (j2_artifact_models builds the models from the same file; generic_problems()
                         and `python3 j2_template_lib.py` check every file).
    SpecialisedTemplate  extends one generic ("<artifact>/<section>@generic/1"), keeps every required field of it,
                         may narrow a string to an enum, add fields and rewrite descriptions; made_by, context, used_by.

The library (library/ at the repo root, J2_LIBRARY_DIR overrides) holds every specialised version:
    library/<artifact>/<section-slug>/<template-slug>/v<N>/{spec.json, model.py, schema.json, meta.json}
    library/index.json   the routing table
spec.json is the source. model.py is Python GENERATED by codegen() from it, for people and agents to read; J2 never
imports or execs it: at runtime the class is built from spec.json with pydantic.create_model (build_model). schema.json
is the draft-07 transport schema sent with --json-schema, with the same rules as j2_artifact_models.transport_schema.
Nothing here names an artifact or a section: the artifacts are the ones artifacts/types.json and the templates name.
Versions are immutable: the same sha is the same version, any change is v<N+1>.

The router (route) picks per workflow, like the connector router picks per step, and falls back to the generic one:
same fingerprint -> reuse; a candidate covering everything -> reuse; best coverage >= 0.5 -> extend (new version);
otherwise create; a generated spec that fails the checks twice -> generic. The run never blocks.

Python 3.9: Optional/List/Dict.
"""
