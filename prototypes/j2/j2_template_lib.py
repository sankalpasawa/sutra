SETTINGS_PATH = os.path.join(HERE, "templates", "library-settings.json")
_SETTINGS = {}


def settings():
    """templates/library-settings.json (library-settings/1): the word list, the fact shapes and the routing numbers
    the library works with. Read again only when the file changes; code holds none of them."""
    key = (os.path.getmtime(SETTINGS_PATH), os.path.getsize(SETTINGS_PATH))
    if _SETTINGS.get("key") != key:
        with open(SETTINGS_PATH, encoding="utf-8") as f:
            data = json.load(f)
        _SETTINGS.update(key=key, data=data, stop=set(data["stop_words"]),
                         facts=[(re.compile(x["pattern"], re.I), x) for x in data["fact_fields"]])
    return _SETTINGS["data"]


def routing(name):
    """One routing number or rule of the settings file ("extend_min", "generator_attempts", ...)."""
    return settings()["routing"][name]


def routing_rules():
    """The routing rules as the generator reads them: the settings file's sentences with its own numbers in them."""
    r = settings()["routing"]
    fill = {**{k: v for k, v in r.items() if not isinstance(v, (dict, list))},
            "reuse_without_asking_coverage": r["reuse_without_asking"]["coverage"]}
    return [str(x).format(**fill) for x in r["rules"]]


def words(text):
    """The words two texts are compared by: lower case, at least min_word_length letters, none of the stop words (both
    from the settings file)."""
    least = settings()["min_word_length"]
    return {w for w in re.findall(r"[a-z0-9]+", str(text or "").lower()) if len(w) >= least and w not in _SETTINGS["stop"]}


def _ident(text):
    s = re.sub(r"[^a-z0-9]+", "_", str(text or "").lower()).strip("_")
    return ("f_" + s if s[:1].isdigit() else s) or "field"


def _split_list(text):
    return [x.strip() for x in re.split(settings()["list_separator"], text) if x.strip()]


def fact_fields(facts):
    """The fields the charter's own facts name, deterministically, by the fact shapes of the settings file (fact_fields:
    the first pattern that matches a fact is used). "objects": a list of objects, one field per listed name; "values": a
    list of the listed names as an enum. Every name and value is copied from a fact; nothing is invented.
    [(FieldSpec, [ObjectSpec])]."""
    settings()
    out, seen = [], set()
    for fact in facts:
        hit = next(((m, x) for rx, x in _SETTINGS["facts"] for m in [rx.search(fact)] if m), None)
        if hit is None:
            continue
        m, x = hit
        noun = _ident(m.group(1))
        fill = {"noun": noun, "Noun": "".join(p.title() for p in noun.split("_")), "word": m.group(1), "fact": fact}
        name = x["name"].format(**fill)
        if name in seen or not NAME_RE.match(name):
            continue
        if x["makes"] == "objects":
            attrs = [a for a in dict.fromkeys(_ident(a) for a in _split_list(m.group(2))) if NAME_RE.match(a)]
            if not attrs:
                continue
            obj = x["object"].format(**fill)
            seen.add(name)
            out.append((FieldSpec(name=name, type=f"list[{obj}]", required=False, description=x["description"].format(**fill)),
                        [ObjectSpec(name=obj, fields=[FieldSpec(name=a, type="string", required=True,
                                                                description=x["item_description"].format(item=a.replace("_", " "), **fill))
                                                      for a in attrs])]))
        else:
            vals = list(dict.fromkeys(_split_list(m.group(2))))
            if not vals:
                continue
            seen.add(name)
            out.append((FieldSpec(name=name, type="list[string]", required=False, enum=vals,
                                  description=x["description"].format(**fill)), []))
    return out


def fingerprint(artifact, section, business_type, facts, fields=()):
    """sha of (artifact, section, business_type, sorted facts, sorted needed field names)."""
    return sha_of([artifact, section, str(business_type or ""), sorted(set(facts)), sorted(set(fields))])


def make_need(artifact, section, business_type, facts, site, extra_fields=(), workflow="", atom=""):
    """The need of one workflow: artifact + section, business_type, the charter facts behind its items, and the
    fields it asks for (from the facts and the work atom / input documents). Fingerprint by code."""
    facts = sorted(set(str(f) for f in facts if str(f or "").strip()))
    derived = fact_fields(facts) if takes_fact_fields(artifact, section) else []
    fields = sorted(set([f.name for f, _ in derived] + [f.name for f, _ in extra_fields]))
    enums = {}
    for f, _ in derived + list(extra_fields):
        if f.enum:
            enums[f.name] = sorted(set(enums.get(f.name, [])) | set(f.enum))
    return {"artifact": artifact, "section": section, "business_type": str(business_type or NOT_RECORDED),
            "facts": facts, "fields": fields, "field_enums": enums, "site": site or NOT_RECORDED,
            "workflow": workflow, "atom": atom,
            "fingerprint": fingerprint(artifact, section, business_type, facts, fields),
            "_derived": derived + list(extra_fields)}


def takes_fact_fields(artifact, section):
    """The sections that carry the business's offer say so in their template ("fact_fields": true): the facts' own
    lists become fields there. Elsewhere the facts narrow facts_used only."""
    return bool((j2_types.section_template(str(artifact or ""), section) or {}).get("fact_fields"))


def has_field(need, row, name):
    """A template has a needed field when it has the name and, if the need lists values for it (an enum from the
    facts or the LLD), its enum allows every one of them (a field with no enum allows any value)."""
    if name not in (row.get("fields") or []):
        return False
    want = (need.get("field_enums") or {}).get(name)
    have = (row.get("enums") or {}).get(name)
    return not want or have is None or set(want) <= set(have)


def coverage(need, row):
    """(score, facts covered, fields covered): (needed facts it has + needed fields it has) / (all needed). A need
    with nothing in it scores 0: nothing to reuse a template for."""
    facts = set(need["facts"])
    hf = len(facts & set(row.get("facts") or []))
    hd = sum(1 for n in need["fields"] if has_field(need, row, n))
    total = len(facts) + len(need["fields"])
    return (round((hf + hd) / total, 4) if total else 0.0), hf, hd


def candidates(need):
    """Every stored version of the same artifact + section, scored; best first, then newest."""
    out = []
    for e in index()["templates"]:
        if e["artifact"] != need["artifact"] or e["section"] != need["section"]:
            continue
        for v in e["versions"]:
            score, hf, hd = coverage(need, v)
            out.append({"name": e["name"], "slug": e["slug"], "version": v["version"], "score": score,
                        "facts_covered": hf, "fields_covered": hd, "description": v.get("description"),
                        "fields": v.get("fields"), "enums": v.get("enums"),
                        "fingerprint_match": need["fingerprint"] in (v.get("fingerprints") or []),
                        "has_fields": hd == len(need["fields"])})
    out.sort(key=lambda c: (-int(c["fingerprint_match"]), -c["score"], -c["version"], c["name"]))
    return out


