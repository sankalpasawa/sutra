def _enums(t):
    out = {}
    for f in t.fields:
        if f.enum:
            out[f.name] = list(f.enum)
    for o in t.objects:
        for f in o.fields:
            if f.enum:
                out[f"{o.name}.{f.name}"] = list(f.enum)
    return out


