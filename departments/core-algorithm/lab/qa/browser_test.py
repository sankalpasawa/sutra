"""Exercise the generated read-only viewer using actual Chromium, offline set_content."""
from pathlib import Path
import json,sys
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'site'/'index.html').read_text()
checks=[]
def check(label,condition):checks.append({'name':label,'pass':bool(condition)})
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1320,'height':820},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(HTML,wait_until='load')
    check('renders title',page.title()=='Sutra · One Kernel, Expanding System')
    check('initial no semantics',page.locator('#status').inner_text()=='SEMANTICS_MISSING')
    check('all stages visible',page.locator('[data-case]').count()==25)
    check('kernel hash shown',len(page.locator('#hash').inner_text())==64)
    page.locator('[data-case="4"]').click()
    check('stage 04 actual run selected',page.locator('#status').inner_text()=='LOCAL_MODEL_EFFECTS_RECORDED')
    check('ship action appears', 'ship-replacement@1' in page.locator('#actions').inner_text())
    page.locator('[data-tab="trace"]').click()
    check('actual trace listed',page.locator('.event').count()>3)
    page.locator('[data-tab="views"]').click()
    check('four views shown',page.locator('.view').count()==4)
    page.locator('[data-tab="packs"]').click()
    check('input packs listed', '00_goal' in page.locator('#panelBody').inner_text())
    page.locator('[data-case="15"]').click()
    check('candidate built', 'C-ENQUIRY@1' in page.locator('#learn').inner_text())
    page.locator('[data-case="16"]').click()
    check('bad constructor exposed', 'Contract invalid' in page.locator('#learn').inner_text())
    page.locator('[data-case="20"]').click()
    check('cross tenant unknown',page.locator('#status').inner_text()=='QUERY_EVIDENCE')
    page.locator('[data-case="21"]').click()
    check('no standing goal',page.locator('#status').inner_text()=='NO_STANDING_GOAL')
    page.locator('[data-tab="graph"]').click()
    check('graph present',page.locator('svg.graph').count()==1)
    page.locator('[data-case="6"]').click()
    check('new nuance shows both actions',all(x in page.locator('#actions').inner_text() for x in ['ship-replacement@1','notify-customer@1']))
    page.locator('#next').click()
    check('next button works',page.locator('#status').inner_text()=='METHOD_ABSENT')
    page.locator('#prev').click()
    check('previous button works',page.locator('#status').inner_text()=='LOCAL_MODEL_EFFECTS_RECORDED')
    check('no JS errors',not errors)
    page.screenshot(path=str(ROOT/'qa'/'desktop.png'),full_page=True)
    mob=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
    errors_m=[];mob.on('pageerror',lambda e:errors_m.append(str(e)))
    mob.set_content(HTML,wait_until='load')
    mob.locator('[data-case="14"]').click()
    check('mobile status works',mob.locator('#status').inner_text()=='LOCAL_MODEL_EFFECTS_RECORDED')
    check('mobile no page overflow',mob.evaluate('document.documentElement.scrollWidth <= window.innerWidth'))
    check('mobile no JS errors',not errors_m)
    mob.screenshot(path=str(ROOT/'qa'/'mobile.png'),full_page=True)
    browser.close()
report={'checks':checks,'passed':sum(x['pass'] for x in checks),'total':len(checks),'errors':errors,'mobile_errors':errors_m}
(ROOT/'qa'/'browser_qa.json').write_text(json.dumps(report,indent=2)+'\n')
print(report['passed'],'/',report['total'],'viewer browser checks')
if report['passed']!=report['total']:
    print([x for x in checks if not x['pass']]);sys.exit(1)
