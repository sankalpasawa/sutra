"""The frames the app sends, as models (A4.7.3): a contract, and the two frames A4 adds.

The existing producers do NOT build these: the chat's frames stay dicts made where they are made (STR-2, STR-5), and a model per
token is the one thing a stream must not do. The classes exist to be read (schemas/models/frames.schema.json, generated by
`python -m layer_models.frames --write`) and to be checked against what the producers emit (test_layer_models_stream.py). The
frames A4 adds are made as models, validated once where they are made, and go out with `FRAME_ADAPTER.dump_json` from an adapter
built here at import (STR-3).

Frames carry keys beyond the ones named (`model`, `detail`, `code`, ...), so they are `Open` and type only the keys the chat
documents; `type` is a Literal and the discriminator of `ChatFrame`."""
import json
import sys
from pathlib import Path
from typing import Annotated, Any, List, Literal, Optional, Union

from pydantic import Field, TypeAdapter

from .base import Closed, Open

SCHEMA_PATH = Path(__file__).resolve().parent.parent / 'schemas' / 'models' / 'frames.schema.json'


# ---- /api/sessions/stream: SSE events named by `event:`, not by a type key -------------------------------------------------
class Sync(Open):
    """event: sync, the whole index first."""
    sessions: List[dict]


class Changed(Open):
    """event: changed, the sessions that moved."""
    sessions: List[dict]


class Vanished(Open):
    """event: vanished."""
    ids: List[str]


class Tick(Open):
    """event: tick, the keep-alive."""
    now: int


class Row(Open):
    """/sse/{source}: one parsed row of a governance log (the keys vary by log)."""
    ts: Optional[Any] = None


# ---- /ws/chat: a frame with a `type` ---------------------------------------------------------------------------------------
class Start(Open):
    type: Literal['start']
    model: Optional[str] = None


class Session(Open):
    type: Literal['session']
    id: Optional[str] = None


class Token(Open):
    type: Literal['token']
    text: str


class Thinking(Open):
    type: Literal['thinking']


class Tool(Open):
    """phase 'start' carries name, summary, kind; phase 'end' carries ok and output; both carry the id."""
    type: Literal['tool']
    phase: Optional[str] = None
    id: Optional[str] = None
    name: Optional[str] = None
    ok: Optional[bool] = None
    output: Optional[str] = None


class Notice(Open):
    type: Literal['notice']
    text: str


class Done(Open):
    type: Literal['done']
    session: Optional[str] = None
    duration_ms: Optional[Any] = None
    num_turns: Optional[Any] = None
    cost_usd: Optional[Any] = None


class Error(Open):
    type: Literal['error']
    detail: Optional[str] = None


class Stopped(Open):
    type: Literal['stopped']
    session: Optional[str] = None


class Handed(Open):
    type: Literal['handed']


class Queued(Open):
    type: Literal['queued']
    reason: Optional[str] = None


class ModeNote(Open):
    type: Literal['mode_note']


class Chat(Open):
    type: Literal['chat']
    sutra_id: Optional[str] = None


class Provider(Open):
    type: Literal['provider']
    id: Optional[str] = None
    name: Optional[str] = None


class Retry(Open):
    type: Literal['retry']
    detail: Optional[str] = None


class Retrying(Open):
    type: Literal['retrying']
    detail: Optional[str] = None
    attempt: Optional[Any] = None


class Sysinit(Open):
    type: Literal['sysinit']
    model: Optional[str] = None


class Joined(Open):
    type: Literal['joined']


ChatFrame = Annotated[Union[Start, Session, Token, Thinking, Tool, Notice, Done, Error, Stopped, Handed, Queued, ModeNote, Chat,
                            Provider, Retry, Retrying, Sysinit, Joined], Field(discriminator='type')]
CHAT_ADAPTER = TypeAdapter(ChatFrame)
CHAT_TYPES = ('start', 'session', 'token', 'thinking', 'tool', 'notice', 'done', 'error', 'stopped', 'handed', 'queued',
              'mode_note', 'chat', 'provider', 'retry', 'retrying', 'sysinit', 'joined')


# ---- the frames A4 adds ----------------------------------------------------------------------------------------------------
class Models(Closed):
    """event: models on the sessions stream: a model edit reached the registry (A4.7.4)."""
    rev: Annotated[int, Field(ge=0)]
    keys: List[str]


class Progress(Closed):
    """What a streamed answer has shown so far (A4.7.5): names and counts, never half a value."""
    arrived: List[str]
    counts: dict
    faults: List[str]
    pending: List[str]
    done: bool
    bytes: int


#: built once, here; a new frame is made (validated) where it is produced and dumped with this
FRAME_ADAPTER = TypeAdapter(Union[Models, Progress])


def frame_json(frame):
    """A new frame as the JSON text of an event's data line: dumped, never validated again."""
    return FRAME_ADAPTER.dump_json(frame).decode()


# ---- the generated schema --------------------------------------------------------------------------------------------------
def schema_text():
    """The text of schemas/models/frames.schema.json, key for key what the models generate."""
    doc = {
        'title': 'The frames the app sends (A4.7.3)',
        'chat': CHAT_ADAPTER.json_schema(),
        'sessions': {c.__name__.lower(): TypeAdapter(c).json_schema() for c in (Sync, Changed, Vanished, Tick)},
        'log_tail': TypeAdapter(Row).json_schema(),
        'added': {c.__name__.lower(): TypeAdapter(c).json_schema() for c in (Models, Progress)},
    }
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + '\n'


def main(argv):
    if '--write' in argv:
        SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
        SCHEMA_PATH.write_text(schema_text(), encoding='utf-8')
        print('wrote', SCHEMA_PATH)
        return 0
    sys.stdout.write(schema_text())
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
